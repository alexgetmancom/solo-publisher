/**
 * What the public site reads from this Studio, and the files it links to.
 *
 * The site is its own service (alexgetman-site) and has no access to this
 * Studio's database or disk. `GET /api/public/site` is everything it renders:
 * the published posts and what the Studio says the site is. The proxy sends
 * `/media/*` and `/generated/responsive/media-*` here, so the files a post links
 * to are served by the process that wrote them.
 *
 * A Studio with the site turned off still serves the staging media and the
 * video asset route: publishing platforms fetch from those whether or not
 * there is a website.
 */

const NOT_FOUND = () => text("not found\n", 404);

export const publicSiteRoutes: RouteModule = (app, { config, backendDb }) => {
  const cache: SiteCache = { media: new WeakMap(), items: new WeakMap() };
  app.get("/api/public/site", async (c) => {
    if (!config.studio.siteEnabled) return NOT_FOUND();
    const { body, etag } = await publicSiteBody(config, loadPublicSiteFeed(backendDb), cache);
    const headers = { "content-type": "application/json; charset=utf-8", etag, "cache-control": "no-cache" };
    // The site asks every few seconds and the answer rarely changes; a 304
    // spares it parsing the whole archive again.
    if (c.req.header("if-none-match") === etag) return new Response(null, { status: 304, headers });
    return new Response(body, { headers });
  });

  app.on(["GET", "HEAD"], "/media/video/asset/:id", (c) => {
    const id = c.req.param("id");
    // Content-addressed by sha256 (matches videoPublicUrl): the asset id is a
    // small integer and would be trivially enumerable, exposing unpublished
    // Studio uploads. Meta fetches this while it imports a Reel.
    if (!/^[a-f0-9]{64}$/.test(id)) return NOT_FOUND();
    const asset = publicVideoAsset(backendDb, id);
    if (!asset) return NOT_FOUND();
    const file = Bun.file(asset.localPath);
    if (file.size === 0) return NOT_FOUND();
    return new Response(c.req.method === "HEAD" ? null : file, {
      headers: {
        "Content-Type": asset.mimeType || "video/mp4",
        "Content-Length": String(file.size),
        "Cache-Control": "public, max-age=300",
        // No Accept-Ranges: this route always returns the whole file, and
        // advertising range support to an importer that then sends `Range` and
        // gets a 200 back is worse than not advertising it.
        "X-Robots-Tag": "noindex, nofollow",
      },
    });
  });

  app.on(["GET", "HEAD"], "/media/*", async (c) => {
    const requested = decodeURIComponent(c.req.path.slice("/media/".length));
    const staged = requested === "staging" || requested.startsWith("staging/");
    if (!staged && !config.studio.siteEnabled) return NOT_FOUND();
    const root = path.resolve(staged ? config.REMOTE_MEDIA_PATH : path.join(config.SITE_PUBLIC_DIR, "media"));
    const filePath = path.resolve(root, staged ? requested.slice("staging".length).replace(/^\/+/, "") : requested);
    if (filePath !== root && !filePath.startsWith(`${root}${path.sep}`)) return text("forbidden\n", 403);
    const file = Bun.file(filePath);
    if (!(await file.exists())) return NOT_FOUND();
    const headers = new Headers({
      // Replacements change the version key. Historical links without one
      // refresh daily rather than pinning a mutable name in the browser.
      "Cache-Control":
        !staged && versioned(c.req.url) ? "public, max-age=31536000, immutable" : "public, max-age=86400, stale-while-revalidate=604800",
    });
    if (file.type) headers.set("Content-Type", file.type);
    return rangedFileResponse(file, c.req.raw, { headers, headOnly: c.req.method === "HEAD" });
  });

  // IndexNow fetches the key back from the root of the host it pinged for; a
  // key anywhere deeper would only vouch for URLs under that directory. The
  // proxy sends exactly this shape here and every other `.txt` to the site.
  app.get("/:file{[a-f0-9]{32}\\.txt}", (c) => {
    const key = indexNowKey(config);
    if (!key || c.req.param("file") !== `${key}.txt`) return NOT_FOUND();
    return text(`${key}\n`, 200);
  });

  // Responsive variants are generated by the publication worker before the post
  // reaches the feed. Public requests only read the cached file; they never
  // launch ffmpeg or sharp.
  app.get("/generated/responsive/:file", async (c) => {
    if (!config.studio.siteEnabled) return NOT_FOUND();
    const match = /^([A-Za-z0-9._-]+)-(\d{3,4})\.webp$/.exec(c.req.param("file"));
    if (!match || !RESPONSIVE_WIDTHS.map(String).includes(match[2] ?? "")) return NOT_FOUND();
    const cached = Bun.file(path.join(config.SITE_PUBLIC_DIR, "generated/responsive", match[0]));
    if (!(await cached.exists())) return NOT_FOUND();
    return new Response(cached, {
      headers: {
        "Content-Type": "image/webp",
        "Cache-Control": versioned(c.req.url)
          ? "public, max-age=31536000, immutable"
          : "public, max-age=604800, stale-while-revalidate=86400",
      },
    });
  });
};

function versioned(url: string): boolean {
  return /^[a-f0-9]{12}$/.test(new URL(url, "https://site.invalid/").searchParams.get("v") ?? "");
}

type SiteBody = {
  items: FeedItem[];
  identity: string;
  checkedAt: number;
  value: Promise<{ body: string; etag: string; rendered: FeedItem[] }>;
};
type SiteCache = {
  last?: SiteBody;
  media: WeakMap<
    SiteMedia,
    { exists: boolean; poster: boolean; image: Awaited<ReturnType<typeof siteImage>>; value: SiteMedia[]; immutable: boolean }
  >;
  items: WeakMap<FeedItem, { value: FeedItem; immutable: boolean }>;
};

/** The read model already caches the feed for a few seconds and hands back the
 * same array while it does, so the serialised answer is rebuilt only when the
 * feed or the identity actually changed. */
function publicSiteBody(config: BackendConfig, feed: FeedItem[], cache: SiteCache): SiteBody["value"] {
  const previous = cache.last;
  const now = Date.now();
  const identity = JSON.stringify({ en: siteIdentity(config, "en"), ru: siteIdentity(config, "ru") });
  if (previous?.items === feed && previous.identity === identity && now - previous.checkedAt < SITE_FEED_REFRESH_MS) return previous.value;
  const value = Promise.all(feed.map((item) => withServedMedia(config, item, cache))).then(async (items) => {
    const before = await previous?.value.catch(() => undefined);
    if (
      before &&
      previous?.identity === identity &&
      items.length === before.rendered.length &&
      items.every((item, index) => item === before.rendered[index])
    )
      return before;
    const body = `{"site":${identity},"items":${JSON.stringify(items)}}`;
    const etag = `"${crypto.createHash("sha256").update(body).digest("base64url").slice(0, 27)}"`;
    return { body, etag, rendered: items };
  });
  const pending = { items: feed, identity, value, checkedAt: now };
  cache.last = pending;
  void value.catch(() => {
    if (cache.last === pending) delete cache.last;
  });
  return value;
}

function siteIdentity(config: BackendConfig, locale: "en" | "ru") {
  const site = config.studio.site(locale);
  return {
    // An install that has not named itself is named by its own domain, which is
    // true and belongs to nobody else.
    name: site.name || new URL(config.PUBLIC_BASE_URL).host,
    tagline: site.tagline,
    about: site.about,
    bio: site.bio,
    profiles: site.profiles.map(({ label, url }) => ({ label, url })),
    timezone: config.studio.siteTimezone(locale),
  };
}

/** Media is written to disk after a post is published, so the stored list can
 * name a file that is not there yet. The site has no disk to check that against,
 * so the list it gets holds only what this Studio would actually serve. */
async function withServedMedia(config: BackendConfig, item: FeedItem, cache: SiteCache): Promise<FeedItem> {
  const cached = cache.items.get(item);
  if (cached?.immutable) return cached.value;
  const [media, mediaEn] = await Promise.all(
    [item.media, item.media_en].map(async (entries) =>
      (await Promise.all(entries.map((entry) => servedMedia(config, entry, cache)))).flat(),
    ),
  );
  const value = {
    ...item,
    media: media ?? [],
    media_en: mediaEn ?? [],
    image: served(config, item.image) ? item.image : firstImage(media ?? []),
    image_en: served(config, item.image_en) ? item.image_en : firstImage(mediaEn ?? []),
  };
  const immutable =
    [...item.media, ...item.media_en].every((entry) => cache.media.get(entry)?.immutable) &&
    (!item.image || (versioned(item.image) && served(config, item.image))) &&
    (!item.image_en || (versioned(item.image_en) && served(config, item.image_en)));
  const previous = cached?.value;
  if (
    cached &&
    previous &&
    previous.image === value.image &&
    previous.image_en === value.image_en &&
    previous.media.length === value.media.length &&
    previous.media_en.length === value.media_en.length &&
    previous.media.every((entry, index) => entry === value.media[index]) &&
    previous.media_en.every((entry, index) => entry === value.media_en[index])
  ) {
    cached.immutable = immutable;
    return previous;
  }
  cache.items.set(item, { value, immutable });
  return value;
}

async function servedMedia(config: BackendConfig, stored: SiteMedia, cache: SiteCache): Promise<SiteMedia[]> {
  const previous = cache.media.get(stored);
  if (previous?.immutable) return previous.value;
  // The publication manifest also carries worker-only upload ids and disk
  // paths. Only the fields the public renderer consumes cross this boundary.
  const { type, path, poster, width, height, responsive, poster_responsive } = stored;
  const entry: SiteMedia = { type, path, poster, width, height, responsive, poster_responsive };
  const exists = served(config, entry.path);
  const posterExists = !entry.poster || served(config, entry.poster);
  const image =
    exists && posterExists ? await siteImage(config.SITE_PUBLIC_DIR, entry.type === "video" ? entry.poster || "" : entry.path) : undefined;
  const immutable =
    exists &&
    posterExists &&
    versioned(stored.path) &&
    (!stored.poster || versioned(stored.poster)) &&
    (image?.complete === true || (stored.type === "video" && !stored.poster));
  if (previous && previous.exists === exists && previous.poster === posterExists && previous.image === image) {
    previous.immutable = immutable;
    return previous.value;
  }
  let value: SiteMedia[];
  if (!exists) value = [];
  else if (!posterExists) {
    const { poster: _missing, ...rest } = entry;
    value = [rest];
  } else if (!image) value = [entry];
  else
    value = [
      {
        ...entry,
        width: image.width,
        height: image.height,
        ...(entry.type === "video" ? { poster_responsive: image.responsive } : { responsive: image.responsive }),
      },
    ];
  cache.media.set(stored, { exists, poster: posterExists, image, value, immutable });
  return value;
}

function firstImage(media: SiteMedia[]): string | null {
  return media.find((entry) => entry.type !== "video")?.path ?? null;
}

/** Only hits are remembered: a missing file can appear on the next request, a
 * present one is never deleted while its post is live. Media names carry a
 * `?v=<hash>` cache key, so a replaced file arrives under a path not seen yet. */
const servedFiles = new Set<string>();

function served(config: BackendConfig, publicPath: string | null | undefined): boolean {
  if (!publicPath) return false;
  const relative = publicPath.replace(/^\/+/, "").split(/[?#]/, 1)[0] ?? "";
  const filePath = path.join(config.SITE_PUBLIC_DIR, relative);
  if (servedFiles.has(filePath)) return true;
  if (!fs.existsSync(filePath)) return false;
  servedFiles.add(filePath);
  return true;
}
